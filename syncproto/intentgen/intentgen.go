// Package intentgen turns the canonical intent registry (api-specs sync/intents/*.yaml) into the Go
// table in syncproto/intents_gen.go. It is used by cmd/genintents and by the test that keeps the
// checked-in table in step with the registry.
package intentgen

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type file struct {
	Group   string `yaml:"group"`
	Intents []struct {
		Intent       string              `yaml:"intent"`
		IntentV      int                 `yaml:"intent_v"`
		Class        string              `yaml:"class"`
		Owner        string              `yaml:"owner"`
		Permission   *string             `yaml:"permission"`
		AuthorisedBy []string            `yaml:"authorised_online_by"`
		Sessions     []string            `yaml:"sessions"`
		DeviceKinds  []string            `yaml:"device_kinds"`
		Streams      []string            `yaml:"streams"`
		Numbering    string              `yaml:"numbering"`
		Documents    []string            `yaml:"documents"`
		Entities     map[string][]string `yaml:"entities"`
		Records      []string            `yaml:"records"`
		PIIFields    []string            `yaml:"pii_fields"`
	} `yaml:"intents"`
}

func q(s []string) string {
	if len(s) == 0 {
		return "nil"
	}
	parts := make([]string, len(s))
	for i, x := range s {
		parts[i] = fmt.Sprintf("%q", x)
	}
	return "[]string{" + strings.Join(parts, ", ") + "}"
}

// Generate reads every *.yaml under dir and returns the formatted Go source.
func Generate(dir string) ([]byte, error) {
	paths, err := filepath.Glob(filepath.Join(dir, "*.yaml"))
	if err != nil || len(paths) == 0 {
		return nil, fmt.Errorf("intentgen: no intent files under %s", dir)
	}
	sort.Strings(paths)
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/genintents from the api-specs intent registry (sync/intents). DO NOT EDIT.\n\npackage syncproto\n\n")
	b.WriteString("// Intents is the canonical intent registry: the gateway check and the hub structural check.\n")
	b.WriteString("var Intents = map[string]Intent{\n")
	seen := map[string]bool{}
	var names []string
	bodies := map[string]string{}
	for _, p := range paths {
		raw, err := os.ReadFile(p)
		if err != nil {
			return nil, err
		}
		var f file
		if err := yaml.Unmarshal(raw, &f); err != nil {
			return nil, fmt.Errorf("intentgen: %s: %w", p, err)
		}
		for _, in := range f.Intents {
			if seen[in.Intent] {
				return nil, fmt.Errorf("intentgen: intent %s defined twice", in.Intent)
			}
			seen[in.Intent] = true
			perm := ""
			if in.Permission != nil {
				perm = *in.Permission
			}
			var ents []string
			for e, kinds := range in.Entities {
				ents = append(ents, fmt.Sprintf("%q: %s", e, q(kinds)))
			}
			sort.Strings(ents)
			entMap := "nil"
			if len(ents) > 0 {
				entMap = "map[string][]string{" + strings.Join(ents, ", ") + "}"
			}
			names = append(names, in.Intent)
			bodies[in.Intent] = fmt.Sprintf("%q: {Name: %q, Class: %q, Owner: %q, Permission: %q, AuthorisedBy: %s, Kinds: %s, Sessions: %s, Streams: %s, Numbering: %q, Documents: %s, Entities: %s, Records: %s, PIIFields: %s, MaxV: %d},\n",
				in.Intent, in.Intent, in.Class, in.Owner, perm, q(in.AuthorisedBy), q(in.DeviceKinds), q(in.Sessions), q(in.Streams), in.Numbering, q(in.Documents), entMap, q(in.Records), q(in.PIIFields), in.IntentV)
		}
	}
	sort.Strings(names)
	for _, n := range names {
		b.WriteString(bodies[n])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
