// Package entitygen turns the entity registry (api-specs entities/<product>/*.yaml) into the Go table
// in engine/entities_gen.go that the apply state follows (conflict policy per field, tombstones,
// guarded entities). It is used by cmd/genintents and by the test that keeps the checked-in table in
// step with the registry.
package entitygen

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type doc struct {
	Entity    string `yaml:"entity"`
	Policy    string `yaml:"policy"`
	Tombstone bool   `yaml:"tombstone"`
	Guarded   bool   `yaml:"guarded"`
	Fields    map[string]struct {
		Policy string   `yaml:"policy"`
		Group  string   `yaml:"group"`
		Order  []string `yaml:"order"`
		PII    bool     `yaml:"pii"`
	} `yaml:"fields"`
}

// Generate reads every *.yaml one level under dir and returns the formatted Go source.
func Generate(dir string) ([]byte, error) {
	paths, err := filepath.Glob(filepath.Join(dir, "*", "*.yaml"))
	if err != nil || len(paths) == 0 {
		return nil, fmt.Errorf("entitygen: no entity files under %s", dir)
	}
	sort.Strings(paths)
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/genintents from the api-specs entity registry (entities/). DO NOT EDIT.\n\npackage engine\n\n")
	b.WriteString("// registryEntities is the entity registry: the conflict policy of every field of every synced entity.\n")
	b.WriteString("func registryEntities() map[string]EntityDef {\n\treturn map[string]EntityDef{\n")
	seen := map[string]bool{}
	for _, p := range paths {
		raw, err := os.ReadFile(p)
		if err != nil {
			return nil, err
		}
		var d doc
		if err := yaml.Unmarshal(raw, &d); err != nil {
			return nil, fmt.Errorf("entitygen: %s: %w", p, err)
		}
		if d.Entity != strings.TrimSuffix(filepath.Base(p), ".yaml") {
			return nil, fmt.Errorf("entitygen: %s: entity %q does not equal the file name", p, d.Entity)
		}
		if seen[d.Entity] {
			return nil, fmt.Errorf("entitygen: entity %s defined twice", d.Entity)
		}
		seen[d.Entity] = true
		names := make([]string, 0, len(d.Fields))
		for n := range d.Fields {
			names = append(names, n)
		}
		sort.Strings(names)
		fmt.Fprintf(&b, "\t\t%q: {Policy: %q, Tombstone: %v, Guarded: %v, Fields: map[string]FieldDef{\n", d.Entity, d.Policy, d.Tombstone, d.Guarded)
		for _, n := range names {
			f := d.Fields[n]
			order := "nil"
			if len(f.Order) > 0 {
				parts := make([]string, len(f.Order))
				for i, o := range f.Order {
					parts[i] = fmt.Sprintf("%q", o)
				}
				order = "[]string{" + strings.Join(parts, ", ") + "}"
			}
			pii := ""
			if f.PII {
				pii = ", PII: true"
			}
			fmt.Fprintf(&b, "\t\t\t%q: {Policy: %q, Group: %q, Order: %s%s},\n", n, f.Policy, f.Group, order, pii)
		}
		b.WriteString("\t\t}},\n")
	}
	b.WriteString("\t}\n}\n")
	return format.Source(b.Bytes())
}
